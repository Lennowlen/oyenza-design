#!/usr/bin/env node
/**
 * Writes the three platform files from tokens.json.
 *
 *   node tools/gen.mjs           write dist/
 *   node tools/gen.mjs --check   fail when dist/ is out of date or tokens.json is invalid
 *
 * Standard library only, no build step, no dependency. The same input must
 * always give byte-identical output: tools/check.mjs runs it twice and
 * compares.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)));
const TOKENS = join(ROOT, 'tokens.json');
export const DIST = join(ROOT, 'dist');

const COLOR = /^#[0-9a-f]{6}([0-9a-f]{2})?$/;
const LENGTH = /^[0-9]+(\.[0-9]+)?px$/;

class TokenError extends Error {}
const fail = (message) => {
  throw new TokenError(`tokens.json: ${message}`);
};

/** Groups that hold a plain map of name -> colour. */
const COLOR_GROUPS = ['brand'];
/** Groups that hold a plain map of name -> px length. */
const LENGTH_GROUPS = ['radius', 'space', 'type', 'motion', 'touch'];

const isPlainObject = (value) =>
  value !== null && typeof value === 'object' && !Array.isArray(value);

function checkColors(group, value) {
  if (!isPlainObject(value)) fail(`${group} is not an object`);
  for (const [name, color] of Object.entries(value)) {
    if (typeof color !== 'string' || !COLOR.test(color)) {
      fail(`${group}.${name} is ${JSON.stringify(color)}, not a #rrggbb or #rrggbbaa colour`);
    }
  }
}

function checkLengths(group, value, allowFont = false) {
  if (!isPlainObject(value)) fail(`${group} is not an object`);
  for (const [name, length] of Object.entries(value)) {
    if (allowFont && (name.startsWith('font-') || name === 'font')) {
      if (typeof length !== 'string' || !length.trim()) fail(`${group}.${name} is empty`);
      continue;
    }
    if (
      typeof length !== 'string' ||
      (!LENGTH.test(length) && !/^[0-9]+ms$/.test(length) && !/^cubic-bezier\(/.test(length))
    ) {
      fail(`${group}.${name} is ${JSON.stringify(length)}, not a px length or cubic-bezier()`);
    }
  }
}

/** Fails on anything the generator would silently drop. */
export function validate(tokens) {
  if (tokens.version !== 1) fail(`unknown version ${tokens.version} (this generator reads 1)`);
  for (const group of COLOR_GROUPS) checkColors(group, tokens[group]);
  for (const group of LENGTH_GROUPS) checkLengths(group, tokens[group], group === 'type');

  if (!isPlainObject(tokens.app)) fail('app is not an object');
  for (const scheme of ['light', 'dark']) {
    checkColors(`app.${scheme}`, tokens.app[scheme]);
    for (const key of Object.keys(tokens.app.light)) {
      if (!(key in tokens.app[scheme])) fail(`app.${scheme}.${key} is missing (app.light has it)`);
    }
    for (const key of Object.keys(tokens.app[scheme])) {
      if (!(key in tokens.app.light)) fail(`app.${scheme}.${key} is not in app.light`);
    }
  }

  if (!isPlainObject(tokens.island)) fail('island is not an object');
  for (const [id, look] of Object.entries(tokens.island)) {
    if (!isPlainObject(look)) fail(`island.${id} is not an object`);
    for (const key of ['ground', 'ink', 'accent', 'border', 'wash']) {
      if (!(key in look)) fail(`island.${id}.${key} is missing`);
      if (!COLOR.test(look[key])) fail(`island.${id}.${key} is ${JSON.stringify(look[key])}, not a colour`);
    }
    for (const key of ['light', 'floating']) {
      if (typeof look[key] !== 'boolean') fail(`island.${id}.${key} must be true or false`);
    }
  }

  if (!isPlainObject(tokens.elevation)) fail('elevation is not an object');
  for (const [name, shadow] of Object.entries(tokens.elevation)) {
    if (typeof shadow !== 'string' || !/^[0-9-]/.test(shadow)) fail(`elevation.${name} is not a shadow`);
  }
  return tokens;
}

/** "#f0892e" and "#f0892ecc" as a CSS value; the file keeps the alpha hex. */
const cssColor = (color) => color;

/** 0xFFF0892E style Int literal, the shape the Android island already uses. */
export function kotlinInt(color) {
  const hex = color.slice(1);
  const argb = hex.length === 8 ? hex : `ff${hex}`;
  return `0x${argb.toUpperCase()}.toInt()`;
}

/** 0xFFF0892E style u32 for `poni_core`, which stores island colours as ARGB. */
export function rustInt(color) {
  const hex = color.slice(1);
  const argb = hex.length === 8 ? hex : `ff${hex}`;
  return `0x${argb.toUpperCase()}`;
}

const kebab = (text) => text.replace(/[^a-zA-Z0-9]+/g, '-').toLowerCase();
const kotlinName = (text) =>
  kebab(text).split('-').filter(Boolean).map((part) => part.toUpperCase()).join('_');

function header() {
  return [
    '/* Generated by oyenza-design tools/gen.mjs from tokens.json.',
    '   Do not edit this file: edit tokens.json and run `node tools/gen.mjs`. */',
  ].join('\n');
}

export function renderCss(tokens) {
  const lines = [header(), ':root {'];
  for (const [name, color] of Object.entries(tokens.brand)) {
    lines.push(`  --oy-brand-${kebab(name)}: ${cssColor(color)};`);
  }
  for (const [name, color] of Object.entries(tokens.app.light)) {
    lines.push(`  --oy-app-${kebab(name)}: ${cssColor(color)};`);
  }
  for (const group of ['radius', 'space', 'type', 'motion', 'elevation', 'touch']) {
    const prefix = group === 'elevation' ? 'shadow' : group === 'touch' ? 'touch' : group;
    for (const [name, value] of Object.entries(tokens[group])) {
      lines.push(`  --oy-${prefix}-${kebab(name)}: ${value};`);
    }
  }
  lines.push('  color-scheme: light;', '}', '');

  lines.push('[data-theme="dark"] {');
  for (const [name, color] of Object.entries(tokens.app.dark)) {
    lines.push(`  --oy-app-${kebab(name)}: ${cssColor(color)};`);
  }
  lines.push('  color-scheme: dark;', '}', '');

  for (const [id, look] of Object.entries(tokens.island)) {
    lines.push(`[data-island="${id}"] {`);
    for (const key of ['ground', 'ink', 'accent', 'accent-ink', 'border', 'wash']) {
      if (key in look) lines.push(`  --oy-island-${kebab(key)}: ${cssColor(look[key])};`);
    }
    lines.push('}', '');
  }
  return lines.join('\n');
}

export function renderKotlin(tokens) {
  const lines = [
    'package id.oyenza.core',
    '',
    '/**',
    ' * The shared Oyenza palette, generated from oyenza-design/tokens.json.',
    ' *',
    ' * Do not edit: edit tokens.json, run `node tools/gen.mjs`, and copy this file',
    ' * over. DioramaTheme reads its four looks from here, so the phone and the',
    ' * desktop are the same island.',
    ' */',
    'object OyenzaTokens {',
    '',
    '    // brand',
  ];
  for (const [name, color] of Object.entries(tokens.brand)) {
    lines.push(`    const val ${kotlinName(name)} = ${kotlinInt(color)}`);
  }
  lines.push('', '    // the island, one look per theme');
  for (const [id, look] of Object.entries(tokens.island)) {
    for (const key of ['ground', 'ink', 'accent', 'accent-ink', 'border', 'wash']) {
      if (key in look) {
        lines.push(`    const val ISLAND_${kotlinName(id)}_${kotlinName(key)} = ${kotlinInt(look[key])}`);
      }
    }
    lines.push(`    const val ISLAND_${kotlinName(id)}_LIGHT = ${look.light}`);
    lines.push(`    const val ISLAND_${kotlinName(id)}_FLOATING = ${look.floating}`);
    lines.push('');
  }
  lines.push('    // the app surface behind the island');
  for (const [name, color] of Object.entries(tokens.app.light)) {
    lines.push(`    const val APP_${kotlinName(name)} = ${kotlinInt(color)}`);
  }
  lines.push('', '    // sizes in dp');
  for (const [name, value] of Object.entries(tokens.radius)) {
    if (value.endsWith('px')) lines.push(`    const val RADIUS_${kotlinName(name)}_DP = ${value.slice(0, -2)}f`);
  }
  for (const [name, value] of Object.entries(tokens.space)) {
    lines.push(`    const val SPACE_${kotlinName(name)}_DP = ${value.slice(0, -2)}f`);
  }
  for (const [name, value] of Object.entries(tokens.touch)) {
    lines.push(`    const val TOUCH_${kotlinName(name)}_DP = ${value.slice(0, -2)}f`);
  }
  lines.push('', '    // motion, in milliseconds');
  for (const [name, value] of Object.entries(tokens.motion)) {
    if (value.endsWith('ms')) lines.push(`    const val MOTION_${kotlinName(name)}_MS = ${value.slice(0, -2)}`);
  }
  lines.push('}', '');
  return lines.join('\n');
}

export function renderRust(tokens) {
  const lines = [
    '//! The shared Oyenza palette, generated from oyenza-design/tokens.json.',
    '//!',
    '//! Do not edit: edit tokens.json, run `node tools/gen.mjs`, and copy this',
    '//! file over. `look.rs` reads the island colours from here, so the desktop',
    '//! and the phone are the same island.',
    '',
  ];
  lines.push('use crate::oyen::{FOLD_ORANGE, ORANGE};', '');
  for (const [id, look] of Object.entries(tokens.island)) {
    lines.push(`pub const ${kotlinName(id)}_GROUND: u32 = ${rustInt(look.ground)};`);
    lines.push(`pub const ${kotlinName(id)}_INK: u32 = ${rustInt(look.ink)};`);
    lines.push(`pub const ${kotlinName(id)}_ACCENT: u32 = ${rustInt(look.accent)};`);
    if ('accent-ink' in look) lines.push(`pub const ${kotlinName(id)}_ACCENT_INK: u32 = ${rustInt(look['accent-ink'])};`);
    lines.push(`pub const ${kotlinName(id)}_BORDER: u32 = ${rustInt(look.border)};`);
    lines.push(`pub const ${kotlinName(id)}_WASH: u32 = ${rustInt(look.wash)};`);
    lines.push('');
  }
  for (const [name, color] of Object.entries(tokens.app.light)) {
    lines.push(`pub const APP_${kotlinName(name)}: u32 = ${rustInt(color)};`);
  }
  lines.push('', '/// Oyen\'s orange, kept as a name of its own for the marks that draw with it.');
  lines.push('pub const BRAND_ORANGE: u32 = ORANGE;');
  lines.push('pub const BRAND_FOLD: u32 = FOLD_ORANGE;', '');
  return lines.join('\n');
}

/** name -> file content, the whole of dist/. */
export function render(tokens) {
  return {
    'tokens.css': renderCss(tokens),
    'OyenzaTokens.kt': renderKotlin(tokens),
    'oyenza_tokens.rs': renderRust(tokens),
  };
}

export function build() {
  const tokens = validate(JSON.parse(readFileSync(TOKENS, 'utf8')));
  return render(tokens);
}

function main() {
  const check = process.argv.includes('--check');
  let files;
  try {
    files = build();
  } catch (error) {
    if (error instanceof TokenError) {
      console.error(error.message);
      process.exit(1);
    }
    throw error;
  }
  mkdirSync(DIST, { recursive: true });
  let stale = 0;
  for (const [name, content] of Object.entries(files)) {
    const target = join(DIST, name);
    if (check) {
      let current = null;
      try {
        current = readFileSync(target, 'utf8');
      } catch {}
      if (current !== content) {
        console.error(`dist/${name} is out of date; run node tools/gen.mjs`);
        stale += 1;
      }
    } else {
      writeFileSync(target, content);
      console.log(`wrote dist/${name} (${content.length} bytes)`);
    }
  }
  if (check && stale) process.exit(1);
  if (check) console.log('dist/ matches tokens.json');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
